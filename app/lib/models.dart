import 'dart:math';

/// Mirrors agent/buttons.json. The agent validates everything on save, so these classes only carry data.
class DeckButton {
  String id;
  String label;
  String type; // hotkey | open | obs | game | page | widget | plugin
  String? color; // #rrggbb
  String? icon; // file name served by the agent at /icon/<name>
  String? game; // game: id from the PC's game scan
  String? page; // page: name of the page to switch to
  String? keys; // hotkey
  String? target; // open
  String? action; // obs: scene | toggleMute | toggleStream | toggleRecord; plugin: the plugin's action id
  String? plugin; // plugin id (folder name in agent/plugins)
  Map<String, dynamic> params; // plugin action fields
  String? name; // obs scene/input name
  String? widget; // widget: clock | cpu | ram | gpu | media | volume | timer | counter | weather
  int? minutes; // timer widget
  String? city; // weather widget

  DeckButton({required this.id, required this.label, required this.type, this.color, this.icon, this.game, this.page, this.keys, this.target, this.action, this.name, this.widget, this.minutes, this.city, this.plugin, Map<String, dynamic>? params}) : params = params ?? {};

  factory DeckButton.blank() => DeckButton(id: 'b${DateTime.now().millisecondsSinceEpoch}${Random().nextInt(1000)}', label: 'Novo', type: 'hotkey', keys: 'ctrl+c');

  factory DeckButton.fromJson(Map<String, dynamic> j) => DeckButton(
        id: j['id'],
        label: j['label'],
        type: j['type'],
        color: j['color'],
        icon: j['icon'],
        game: j['game'],
        page: j['page'],
        keys: j['keys'],
        target: j['target'],
        action: j['action'],
        name: j['name'],
        widget: j['widget'],
        minutes: j['minutes'],
        city: j['city'],
        plugin: j['plugin'],
        params: j['params'] == null ? null : Map<String, dynamic>.from(j['params']),
      );

  Map<String, dynamic> toJson() => {
        'id': id,
        'label': label,
        'type': type,
        if (color != null) 'color': color,
        if (icon != null) 'icon': icon,
        if (type == 'game') 'game': game,
        if (type == 'page') 'page': page,
        if (type == 'hotkey') 'keys': keys,
        if (type == 'open') 'target': target,
        if (type == 'obs' || type == 'plugin') 'action': action,
        if (type == 'plugin') 'plugin': plugin,
        if (type == 'plugin') 'params': params,
        if (type == 'obs' && (action == 'scene' || action == 'toggleMute')) 'name': name,
        if (type == 'widget') 'widget': widget,
        if (type == 'widget' && widget == 'timer') 'minutes': minutes ?? 5,
        if (type == 'widget' && widget == 'weather') 'city': city,
      };

  DeckButton copy() => DeckButton.fromJson(toJson());
}

class DeckPage {
  String name;
  List<DeckButton> buttons;
  final bool auto; // the Jogos page, generated by the PC from installed games; never saved
  final String? template; // 'obs' marks the page the OBS switch in Configurações adds and removes
  DeckPage({required this.name, required this.buttons, this.auto = false, this.template});

  factory DeckPage.fromJson(Map<String, dynamic> j) =>
      DeckPage(name: j['name'], auto: j['auto'] == true, template: j['template'], buttons: [for (final b in j['buttons']) DeckButton.fromJson(b)]);

  Map<String, dynamic> toJson() => {'name': name, if (auto) 'auto': true, if (template != null) 'template': template, 'buttons': [for (final b in buttons) b.toJson()]};
}

class GameInfo {
  final String id, label, source;
  final String? icon;
  GameInfo(this.id, this.label, this.source, this.icon);
  factory GameInfo.fromJson(Map<String, dynamic> j) => GameInfo(j['id'], j['label'], j['source'], j['icon']);
}

/// Shown in Configurações before the user applies the creator's preset.
class PresetInfo {
  final String name, version, updatedAt;
  final int pages, buttons;
  PresetInfo(this.name, this.version, this.updatedAt, this.pages, this.buttons);
  factory PresetInfo.fromJson(Map<String, dynamic> j) => PresetInfo(j['name'], j['version'], j['updatedAt'], j['pages'], j['buttons']);
}

class DeckConfig {
  int columns;
  List<DeckPage> pages;
  List<String> hiddenGames;
  final List<GameInfo> games;
  final bool scanning;
  final bool gamesTab, obsPage, widgetsPage, setupDone; // changed only through Configurações, never by a save
  final PresetInfo? creatorPreset;
  final List<PluginInfo> plugins;
  DeckConfig({
    required this.columns,
    required this.pages,
    this.hiddenGames = const [],
    this.games = const [],
    this.scanning = false,
    this.gamesTab = false,
    this.obsPage = false,
    this.widgetsPage = false,
    this.setupDone = true,
    this.creatorPreset,
    this.plugins = const [],
  });

  factory DeckConfig.fromJson(Map<String, dynamic> j) => DeckConfig(
        columns: j['columns'] ?? 3,
        pages: [for (final p in j['pages']) DeckPage.fromJson(p)],
        hiddenGames: [for (final g in j['hiddenGames'] ?? const []) g as String],
        games: [for (final g in j['games'] ?? const []) GameInfo.fromJson(g)],
        scanning: j['scanning'] == true,
        gamesTab: j['features']?['games'] == true,
        obsPage: j['features']?['obs'] == true,
        widgetsPage: j['features']?['widgets'] == true,
        setupDone: j['setupDone'] != false,
        creatorPreset: j['creatorPreset'] == null ? null : PresetInfo.fromJson(j['creatorPreset']),
        plugins: [for (final p in j['plugins'] ?? const []) PluginInfo.fromJson(p)],
      );

  /// What gets saved: only the user's pages. hiddenGames goes along so saving from the phone never un-hides games.
  Map<String, dynamic> toJson() => {
        'columns': columns,
        'pages': [for (final p in pages.where((p) => !p.auto)) p.toJson()],
        'hiddenGames': hiddenGames,
      };

  DeckConfig copy() => DeckConfig(
        columns: columns,
        pages: [for (final p in pages) DeckPage.fromJson(p.toJson())],
        hiddenGames: [...hiddenGames],
        games: games,
        scanning: scanning,
        gamesTab: gamesTab,
        obsPage: obsPage,
        widgetsPage: widgetsPage,
        setupDone: setupDone,
        creatorPreset: creatorPreset,
        plugins: plugins,
      );
}

/// What the QR code carries: the same link that opens the deck in a browser, http://IP:PORT/?t=TOKEN.
class Pairing {
  final String host;
  final int port;
  final String token;
  const Pairing(this.host, this.port, this.token);

  static Pairing? parse(String text) {
    final uri = Uri.tryParse(text.trim());
    final token = uri?.queryParameters['t'];
    if (uri == null || uri.scheme != 'http' || uri.host.isEmpty || token == null || token.isEmpty) return null;
    return Pairing(uri.host, uri.hasPort ? uri.port : 3000, token);
  }

  Pairing withHost(String h) => Pairing(h, port, token);

  @override
  String toString() => 'http://$host:$port/?t=$token';
}

/// A plugin installed on the PC and the form of each of its actions (from its plugin.json).
class PluginInfo {
  final String id, name;
  final Map<String, PluginAction> actions;
  PluginInfo(this.id, this.name, this.actions);
  factory PluginInfo.fromJson(Map<String, dynamic> j) => PluginInfo(j['id'], j['name'], {
        for (final e in (j['actions'] as Map<String, dynamic>).entries) e.key: PluginAction.fromJson(e.value),
      });
}

class PluginAction {
  final String label;
  final String? description;
  final List<PluginField> fields;
  PluginAction(this.label, this.description, this.fields);
  factory PluginAction.fromJson(Map<String, dynamic> j) =>
      PluginAction(j['label'], j['description'], [for (final f in j['fields'] ?? const []) PluginField.fromJson(f)]);
}

class PluginField {
  final String key, label, type;
  final String? placeholder;
  final List<String> options;
  final Object? defaultValue;
  final bool required;
  PluginField(this.key, this.label, this.type, this.placeholder, this.options, this.defaultValue, this.required);
  factory PluginField.fromJson(Map<String, dynamic> j) => PluginField(j['key'], j['label'], j['type'], j['placeholder'],
      [for (final o in j['options'] ?? const []) o.toString()], j['default'], j['required'] == true);
}

/// One live key reading sent by the PC every second.
class LiveValue {
  final String text;
  final String? sub;
  final double? progress;
  final bool alert;
  LiveValue(this.text, this.sub, this.progress, this.alert);
  factory LiveValue.fromJson(Map<String, dynamic> j) =>
      LiveValue(j['text'] ?? '…', j['sub'], (j['progress'] as num?)?.toDouble(), j['alert'] == true);
}

