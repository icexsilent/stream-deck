import 'dart:math';

/// Mirrors agent/buttons.json. The agent validates everything on save, so these classes only carry data.
class DeckButton {
  String id;
  String label;
  String type; // hotkey | open | obs | game | page
  String? color; // #rrggbb
  String? icon; // file name served by the agent at /icon/<name>
  String? game; // game: id from the PC's game scan
  String? page; // page: name of the page to switch to
  String? keys; // hotkey
  String? target; // open
  String? action; // obs: scene | toggleMute | toggleStream | toggleRecord
  String? name; // obs scene/input name

  DeckButton({required this.id, required this.label, required this.type, this.color, this.icon, this.game, this.page, this.keys, this.target, this.action, this.name});

  factory DeckButton.blank() => DeckButton(id: 'b${DateTime.now().millisecondsSinceEpoch}${Random().nextInt(1000)}', label: 'Novo', type: 'hotkey', keys: 'ctrl+c');

  factory DeckButton.fromJson(Map<String, dynamic> j) => DeckButton(
        id: j['id'],
        label: j['label'],
        type: j['type'],
        color: j['color'],
        icon: j['icon'],
        game: j['game'],
        page: j['page'],
        keys: j['keys'],
        target: j['target'],
        action: j['action'],
        name: j['name'],
      );

  Map<String, dynamic> toJson() => {
        'id': id,
        'label': label,
        'type': type,
        if (color != null) 'color': color,
        if (icon != null) 'icon': icon,
        if (type == 'game') 'game': game,
        if (type == 'page') 'page': page,
        if (type == 'hotkey') 'keys': keys,
        if (type == 'open') 'target': target,
        if (type == 'obs') 'action': action,
        if (type == 'obs' && (action == 'scene' || action == 'toggleMute')) 'name': name,
      };

  DeckButton copy() => DeckButton.fromJson(toJson());
}

class DeckPage {
  String name;
  List<DeckButton> buttons;
  final bool auto; // the Jogos page, generated by the PC from installed games; never saved
  DeckPage({required this.name, required this.buttons, this.auto = false});

  factory DeckPage.fromJson(Map<String, dynamic> j) =>
      DeckPage(name: j['name'], auto: j['auto'] == true, buttons: [for (final b in j['buttons']) DeckButton.fromJson(b)]);

  Map<String, dynamic> toJson() => {'name': name, if (auto) 'auto': true, 'buttons': [for (final b in buttons) b.toJson()]};
}

class GameInfo {
  final String id, label, source;
  final String? icon;
  GameInfo(this.id, this.label, this.source, this.icon);
  factory GameInfo.fromJson(Map<String, dynamic> j) => GameInfo(j['id'], j['label'], j['source'], j['icon']);
}

class DeckConfig {
  int columns;
  List<DeckPage> pages;
  List<String> hiddenGames;
  final List<GameInfo> games;
  final bool scanning;
  DeckConfig({required this.columns, required this.pages, this.hiddenGames = const [], this.games = const [], this.scanning = false});

  factory DeckConfig.fromJson(Map<String, dynamic> j) => DeckConfig(
        columns: j['columns'] ?? 3,
        pages: [for (final p in j['pages']) DeckPage.fromJson(p)],
        hiddenGames: [for (final g in j['hiddenGames'] ?? const []) g as String],
        games: [for (final g in j['games'] ?? const []) GameInfo.fromJson(g)],
        scanning: j['scanning'] == true,
      );

  /// What gets saved: only the user's pages. hiddenGames goes along so saving from the phone never un-hides games.
  Map<String, dynamic> toJson() => {
        'columns': columns,
        'pages': [for (final p in pages.where((p) => !p.auto)) p.toJson()],
        'hiddenGames': hiddenGames,
      };

  DeckConfig copy() => DeckConfig(
        columns: columns,
        pages: [for (final p in pages) DeckPage.fromJson(p.toJson())],
        hiddenGames: [...hiddenGames],
        games: games,
        scanning: scanning,
      );
}

/// What the QR code carries: the same link that opens the deck in a browser, http://IP:PORT/?t=TOKEN.
class Pairing {
  final String host;
  final int port;
  final String token;
  const Pairing(this.host, this.port, this.token);

  static Pairing? parse(String text) {
    final uri = Uri.tryParse(text.trim());
    final token = uri?.queryParameters['t'];
    if (uri == null || uri.scheme != 'http' || uri.host.isEmpty || token == null || token.isEmpty) return null;
    return Pairing(uri.host, uri.hasPort ? uri.port : 3000, token);
  }

  Pairing withHost(String h) => Pairing(h, port, token);

  @override
  String toString() => 'http://$host:$port/?t=$token';
}
